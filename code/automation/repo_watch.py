#!/usr/bin/env python3
"""Watch the Python libraries we depend on for updates and risks.

Usage:
    python code/automation/repo_watch.py [--dry-run]

The script reads code/requirements.txt, checks PyPI for each pinned package,
and writes a dated report to knowledge/20-Repo-Watch/.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from datetime import datetime
from importlib.metadata import version as installed_version
from pathlib import Path
from typing import Dict, List, Optional
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

CODE_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(CODE_DIR))

from automation import read_recent_lessons, write_note
from automation.constants import REQUIREMENTS_PATH
from automation.vault import log_session

REPO_ROOT = CODE_DIR.parent
USER_AGENT = "M7-Repo-Watch/1.0 (local automation)"


def _parse_requirements(path: Path) -> Dict[str, str]:
    """Return a dict of package name → pinned version string from requirements.txt."""
    deps: Dict[str, str] = {}
    if not path.exists():
        return deps
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        # Match "pkg==1.2.3" or "pkg>=1.2.3" etc.
        m = re.match(r"^([a-zA-Z0-9_\-]+)\s*([<>=!~]+)\s*([^\s;]+)", line)
        if m:
            deps[m.group(1).lower()] = m.group(3)
    return deps


def _get_pypi_info(package: str) -> Optional[dict]:
    """Fetch package metadata from PyPI JSON API."""
    url = f"https://pypi.org/pypi/{package}/json"
    req = Request(url, headers={"User-Agent": USER_AGENT})
    try:
        with urlopen(req, timeout=15) as response:  # noqa: S310
            return json.loads(response.read().decode("utf-8"))
    except (HTTPError, URLError, TimeoutError, json.JSONDecodeError):
        return None


def _load_config() -> dict:
    """Load repo-watch config (packages of interest + notes)."""
    config_path = CODE_DIR / "automation" / "repo_watch_config.json"
    if config_path.exists():
        return json.loads(config_path.read_text(encoding="utf-8"))
    return {"packages_of_interest": [], "notes": {}}


def _installed_version(package: str) -> Optional[str]:
    """Best-effort installed version using importlib.metadata."""
    try:
        return installed_version(package)
    except Exception:  # noqa: BLE001
        return None


def _build_report(*, dry_run: bool = False) -> str:
    """Compose the markdown body of the repo watch report."""
    today = datetime.now().strftime("%Y-%m-%d")
    deps = _parse_requirements(REQUIREMENTS_PATH)
    config = _load_config()
    notes = config.get("notes", {})
    interesting = {p.lower() for p in config.get("packages_of_interest", [])}

    lines = [
        f"# Repo Watch — {today}",
        "",
        "Generated by `/repo-watch`.",
        "",
        f"- Source: `{REQUIREMENTS_PATH.relative_to(REPO_ROOT)}`",
        f"- Packages pinned: {len(deps)}",
        "",
        "---",
        "",
        "## Dependency status",
        "",
        "| Package | Pinned | Installed | Latest | Note |",
        "|---|---|---|---|---|",
    ]

    updates: List[str] = []
    risks: List[str] = []

    for pkg in sorted(deps):
        pinned = deps[pkg]
        installed = _installed_version(pkg) or "n/a"
        info = _get_pypi_info(pkg)
        if info is None:
            latest = "(unreachable)"
            note = "PyPI lookup failed."
        else:
            latest = info["info"].get("version", "unknown")
            note = notes.get(pkg, "")

        status = ""
        if latest not in ("(unreachable)", "unknown") and pinned != latest:
            status = f"update available ({latest})"
            updates.append(f"- **{pkg}**: pinned {pinned} → latest {latest}")
        if note:
            risks.append(f"- **{pkg}**: {note}")

        lines.append(f"| {pkg} | {pinned} | {installed} | {latest} | {note or status or '—'} |")

    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("## Packages of interest")
    lines.append("")
    if interesting:
        for pkg in sorted(interesting):
            pinned = deps.get(pkg, "not pinned")
            info = _get_pypi_info(pkg)
            latest = info["info"].get("version", "unknown") if info else "(unreachable)"
            note = notes.get(pkg, "")
            lines.append(f"- **{pkg}** (pinned {pinned}, latest {latest}){f' — {note}' if note else ''}")
    else:
        lines.append("_(no packages of interest configured)_")
    lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("## Update summary")
    lines.append("")
    if updates:
        lines.extend(updates)
    else:
        lines.append("_All pinned packages match their latest known versions, or PyPI was unreachable._")
    lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("## Risk notes")
    lines.append("")
    if risks:
        lines.extend(risks)
    else:
        lines.append("_No specific compatibility notes recorded._")
    lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("## Active lessons")
    lines.append("")
    lessons = read_recent_lessons(n=5)
    lines.append(lessons if lessons.strip() else "_(no lessons yet)_")
    lines.append("")

    return "\n".join(lines)


def main(argv: Optional[List[str]] = None) -> int:
    """Generate and save the dependency watch report."""
    parser = argparse.ArgumentParser(description="Watch dependencies for updates and risks.")
    parser.add_argument("--dry-run", action="store_true", help="Print to stdout instead of writing to vault")
    args = parser.parse_args(argv)

    body = _build_report(dry_run=args.dry_run)

    if args.dry_run:
        print(body)
        return 0

    today = datetime.now().strftime("%Y-%m-%d")
    path = write_note(
        "repo_watch",
        f"{today}.md",
        body,
        frontmatter={"date": today, "source": "repo-watch"},
    )
    log_session("repo-watch", path)
    print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
