#!/usr/bin/env python3
"""Paper helper — suggest improvements to the M7 research paper.

Usage:
    python code/automation/improve_paper.py [--dry-run]

The script reads paper/cross_modal_correspondence.tex, cross-checks claims
against available results, and writes suggestions to knowledge/40-Paper/.
It never edits the paper itself.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import datetime
from pathlib import Path
from typing import List, Optional

CODE_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(CODE_DIR))

from automation import read_recent_lessons, write_note
from automation.constants import PAPER_PATH, STEERING_PATH
from automation.vault import list_recent_notes, log_session, read_note

REPO_ROOT = CODE_DIR.parent


def _load_paper() -> str:
    if not PAPER_PATH.exists():
        return ""
    return PAPER_PATH.read_text(encoding="utf-8", errors="ignore")


def _load_latest_consultant_summary() -> str:
    """Read the most recent consultant report, stripping frontmatter."""
    notes = list_recent_notes("consultant", n=1)
    if not notes:
        return ""
    text = read_note(notes[0], max_chars=3000)
    text = re.sub(r"^---\n.*?---\n", "", text, flags=re.DOTALL)
    return text.strip()


def _extract_claims(tex: str) -> List[dict]:
    """Heuristic extraction of numeric and strong claims."""
    claims: List[dict] = []
    # Sentences containing digits or percent signs.
    sentences = re.split(r"(?<=[.!?])\s+", tex)
    for sent in sentences:
        if re.search(r"\b\d+(?:\.\d+)?%?\b", sent):
            claims.append({"text": sent.strip(), "type": "numeric"})
    return claims


def _check_references(tex: str) -> List[str]:
    """Find citation commands and note any obvious gaps."""
    issues: List[str] = []
    cite_count = len(re.findall(r"\\cite\{[^}]+\}", tex))
    if cite_count == 0:
        issues.append("No `\\cite{...}` commands found — verify the paper uses a different citation style or is incomplete.")
    ref_count = len(re.findall(r"\\ref\{[^}]+\}", tex))
    if ref_count == 0:
        issues.append("No `\\ref{...}` commands found — figures/tables may be unreferenced.")
    return issues


def _build_report(*, dry_run: bool = False) -> str:
    """Compose the markdown body of the paper helper report."""
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    tex = _load_paper()

    lines = [
        f"# Paper Helper Report — {now}",
        "",
        "Generated by `/improve-paper`.",
        "",
        "This report **suggests** improvements; it does not edit the paper.",
        "",
    ]

    if not tex:
        lines.extend([
            "## Status",
            "",
            f"**No paper found** at `{PAPER_PATH.relative_to(REPO_ROOT)}`. Nothing to review.",
            "",
        ])
        return "\n".join(lines)

    lines.append(f"- Source: `{PAPER_PATH.relative_to(REPO_ROOT)}`")
    lines.append(f"- Length: {len(tex)} characters, ~{len(tex.split())} words")
    lines.append("")

    # Claim / number checks.
    claims = _extract_claims(tex)
    lines.append("## Claims needing data check")
    lines.append("")
    if claims:
        lines.append(f"Found {len(claims)} sentences with numeric claims. A few examples:")
        lines.append("")
        for claim in claims[:10]:
            text = claim["text"]
            if len(text) > 200:
                text = text[:200] + "..."
            lines.append(f"- `{text}`")
            lines.append("  - status: **needs verification** against results CSV")
            lines.append("")
    else:
        lines.append("_No numeric claims detected._")
    lines.append("")

    # Reference checks.
    lines.append("## Reference / structure checks")
    lines.append("")
    ref_issues = _check_references(tex)
    if ref_issues:
        for issue in ref_issues:
            lines.append(f"- {issue}")
    else:
        lines.append("- Citations and cross-references are present.")
    lines.append("")

    # Overstatement / hedge checks.
    lines.append("## Language checks")
    lines.append("")
    hedge_words = ["significantly", "dramatically", "vastly", "clearly", "robustly"]
    found_hedges = []
    for word in hedge_words:
        count = len(re.findall(rf"\\b{word}\\b", tex, re.IGNORECASE))
        if count:
            found_hedges.append(f"- `{word}`: {count} occurrence(s)")
    if found_hedges:
        lines.append("Strong adverbs detected — verify each is backed by a statistical test:")
        lines.append("")
        lines.extend(found_hedges)
    else:
        lines.append("_No obvious strong adverbs flagged._")
    lines.append("")

    # Latest consultant context.
    consult_summary = _load_latest_consultant_summary()
    lines.append("## Latest results context")
    lines.append("")
    if consult_summary:
        lines.append(consult_summary[:1500])
    else:
        lines.append("_No consultant report available. Run `/consult` first for grounded numbers._")
    lines.append("")

    lines.append("## Suggested next steps")
    lines.append("")
    lines.append("1. Cross-check each numeric claim against the canonical results CSV.")
    lines.append("2. Ensure every figure and table is referenced with `\\ref`.")
    lines.append("3. Replace strong adverbs with measured effect sizes or confidence intervals.")
    lines.append("4. Add missing citations for methods that are not original to this work.")
    lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("## Active lessons")
    lines.append("")
    lessons = read_recent_lessons(n=5)
    lines.append(lessons if lessons.strip() else "_(no lessons yet)_")
    lines.append("")

    return "\n".join(lines)


def main(argv: Optional[List[str]] = None) -> int:
    """Generate and save the paper helper suggestion report."""
    parser = argparse.ArgumentParser(description="Suggest improvements to the research paper.")
    parser.add_argument("--dry-run", action="store_true", help="Print to stdout instead of writing to vault")
    args = parser.parse_args(argv)

    body = _build_report(dry_run=args.dry_run)

    if args.dry_run:
        print(body)
        return 0

    stamp = datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
    path = write_note(
        "paper",
        f"{stamp}.md",
        body,
        frontmatter={"timestamp": stamp, "source": "improve-paper"},
    )
    log_session("improve-paper", path)
    print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
