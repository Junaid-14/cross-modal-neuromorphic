#!/usr/bin/env python3
"""Repo health check — suggest code improvements without editing anything.

Usage:
    python code/automation/improve_repo.py [--dry-run]

The script runs lightweight static checks on Python files and writes findings
to knowledge/60-Patches/.
"""

from __future__ import annotations

import argparse
import ast
import py_compile
import sys
from datetime import datetime
from pathlib import Path
from typing import List, Optional

CODE_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(CODE_DIR))

from automation import read_recent_lessons, write_note
from automation.vault import log_session

REPO_ROOT = CODE_DIR.parent
TARGET_DIRS = ["code", "Models", "Dataloaders", "training", "utils", "tests"]
LARGE_FILE_LINES = 500


EXCLUDED_DIRS = {".venv", "__pycache__", ".git", "node_modules", ".pytest_cache"}


def _collect_python_files() -> List[Path]:
    files: List[Path] = []
    for name in TARGET_DIRS:
        folder = REPO_ROOT / name
        if not folder.exists():
            continue
        for p in folder.rglob("*.py"):
            if not p.is_file():
                continue
            if any(part in EXCLUDED_DIRS for part in p.relative_to(REPO_ROOT).parts):
                continue
            files.append(p)
    return sorted(files)


def _check_compile(path: Path) -> Optional[str]:
    try:
        py_compile.compile(str(path), doraise=True)
        return None
    except py_compile.PyCompileError as exc:
        return f"Compile error: {exc}"


def _missing_docstrings(path: Path) -> List[str]:
    """Return public classes/functions without docstrings."""
    try:
        source = path.read_text(encoding="utf-8", errors="ignore")
        tree = ast.parse(source)
    except SyntaxError:
        return []

    missing: List[str] = []
    for node in ast.iter_child_nodes(tree):
        if isinstance(node, ast.ClassDef):
            if not ast.get_docstring(node):
                missing.append(f"class `{node.name}`")
        elif isinstance(node, ast.FunctionDef):
            if not node.name.startswith("_") and not ast.get_docstring(node):
                missing.append(f"function `{node.name}()`")
    return missing


def _find_todos(path: Path) -> List[str]:
    todos: List[str] = []
    try:
        for i, line in enumerate(path.read_text(encoding="utf-8", errors="ignore").splitlines(), start=1):
            if "TODO" in line or "FIXME" in line:
                todos.append(f"line {i}: {line.strip()}")
    except Exception:  # noqa: BLE001
        pass
    return todos


def _build_report(*, dry_run: bool = False) -> str:
    """Compose the markdown body of the repo health report."""
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    files = _collect_python_files()

    lines = [
        f"# Improver Report — {now}",
        "",
        "Generated by `/improve-repo`.",
        "",
        "This report **suggests** fixes; it does not edit code on its own.",
        "",
        f"- Files scanned: {len(files)}",
        f"- Directories: {', '.join(TARGET_DIRS)}",
        "",
        "---",
        "",
    ]

    compile_errors: List[str] = []
    docstring_gaps: List[str] = []
    large_files: List[str] = []
    todos: List[str] = []

    for path in files:
        rel = path.relative_to(REPO_ROOT)
        err = _check_compile(path)
        if err:
            compile_errors.append(f"- `{rel}`: {err}")

        missing = _missing_docstrings(path)
        if missing:
            docstring_gaps.append(f"- `{rel}`: {', '.join(missing)}")

        try:
            line_count = len(path.read_text(encoding="utf-8", errors="ignore").splitlines())
        except Exception:  # noqa: BLE001
            line_count = 0
        if line_count > LARGE_FILE_LINES:
            large_files.append(f"- `{rel}`: {line_count} lines")

        file_todos = _find_todos(path)
        for todo in file_todos:
            todos.append(f"- `{rel}`: {todo}")

    lines.append("## Compile errors")
    lines.append("")
    if compile_errors:
        lines.extend(compile_errors)
    else:
        lines.append("_No compile errors detected._")
    lines.append("")

    lines.append("## Missing docstrings")
    lines.append("")
    if docstring_gaps:
        lines.extend(docstring_gaps[:30])
        if len(docstring_gaps) > 30:
            lines.append(f"_... and {len(docstring_gaps) - 30} more files._")
    else:
        lines.append("_All scanned public classes/functions have docstrings._")
    lines.append("")

    lines.append("## Large files")
    lines.append("")
    if large_files:
        lines.append(f"Files over {LARGE_FILE_LINES} lines (consider refactoring):")
        lines.append("")
        lines.extend(large_files)
    else:
        lines.append("_No files exceed the size threshold._")
    lines.append("")

    lines.append("## TODO / FIXME notes")
    lines.append("")
    if todos:
        lines.extend(todos[:30])
        if len(todos) > 30:
            lines.append(f"_... and {len(todos) - 30} more._")
    else:
        lines.append("_No TODO or FIXME comments found._")
    lines.append("")

    lines.append("## Suggested fixes")
    lines.append("")
    if compile_errors:
        lines.append("1. Fix compile errors first — they block everything else.")
    if docstring_gaps:
        lines.append(f"2. Add docstrings to {len(docstring_gaps)} public classes/functions.")
    if large_files:
        lines.append(f"3. Consider splitting {len(large_files)} large files into smaller modules.")
    if todos:
        lines.append(f"4. Triage {len(todos)} TODO/FIXME items.")
    if not any([compile_errors, docstring_gaps, large_files, todos]):
        lines.append("_No issues flagged — the repo looks healthy at this granularity._")
    lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("## Active lessons")
    lines.append("")
    lessons = read_recent_lessons(n=5)
    lines.append(lessons if lessons.strip() else "_(no lessons yet)_")
    lines.append("")

    return "\n".join(lines)


def main(argv: Optional[List[str]] = None) -> int:
    """Generate and save the repository health report."""
    parser = argparse.ArgumentParser(description="Generate a code health report.")
    parser.add_argument("--dry-run", action="store_true", help="Print to stdout instead of writing to vault")
    args = parser.parse_args(argv)

    body = _build_report(dry_run=args.dry_run)

    if args.dry_run:
        print(body)
        return 0

    stamp = datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
    path = write_note(
        "patches",
        f"{stamp}.md",
        body,
        frontmatter={"timestamp": stamp, "source": "improve-repo"},
    )
    log_session("improve-repo", path)
    print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
