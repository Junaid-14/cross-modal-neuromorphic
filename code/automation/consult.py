#!/usr/bin/env python3
"""Statistics consultant for the latest M7 experiment results.

Usage:
    python code/automation/consult.py [--dry-run]

The script loads the canonical results CSV, filters duplicates per CLAUDE.md,
computes per-task and per-seed statistics, and writes an interpretation to
knowledge/30-Consultant/.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime
from pathlib import Path
from typing import List, Optional

CODE_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(CODE_DIR))

from automation import read_recent_lessons, write_note
from automation.constants import STEERING_PATH
from automation.vault import log_session

REPO_ROOT = CODE_DIR.parent


def _load_steering() -> dict:
    if not STEERING_PATH.exists():
        return {}
    return json.loads(STEERING_PATH.read_text(encoding="utf-8"))


def _find_results_csv(steering: dict) -> Optional[Path]:
    rel = steering.get("results_csv")
    if not rel:
        return None
    return REPO_ROOT / rel


def _load_results(path: Path) -> Optional[object]:  # pandas DataFrame
    try:
        import pandas as pd
    except ImportError:
        return None
    try:
        df = pd.read_csv(path)
    except Exception:  # noqa: BLE001
        return None
    return df


def _filter_results(df: object) -> object:
    """Apply CLAUDE.md deduplication rules."""
    # Per CLAUDE.md: filter step.isna() then drop_duplicates().
    if "step" in df.columns:
        df = df[df["step"].isna()]
    return df.drop_duplicates()


def _format_number(x) -> str:
    if x is None:
        return "n/a"
    try:
        return f"{float(x):.2f}"
    except (TypeError, ValueError):
        return str(x)


def _build_report(*, dry_run: bool = False) -> str:
    """Compose the markdown body of the consultant report."""
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    steering = _load_steering()
    results_path = _find_results_csv(steering)

    lines = [
        f"# Consultant Report — {now}",
        "",
        "Generated by `/consult`.",
        "",
    ]

    if results_path is None:
        lines.extend([
            "## Status",
            "",
            "**No results yet** — `steering/project_state.json` does not specify a `results_csv`.",
            "",
        ])
        return "\n".join(lines)

    lines.append(f"- Source: `{results_path.relative_to(REPO_ROOT)}`")
    lines.append("")

    df = _load_results(results_path)
    if df is None:
        lines.extend([
            "## Status",
            "",
            f"**No results yet** — could not load `{results_path.name}` (missing or unreadable).",
            "",
        ])
        return "\n".join(lines)

    if len(df) == 0:
        lines.extend([
            "## Status",
            "",
            "**No results yet** — the results CSV is empty.",
            "",
        ])
        return "\n".join(lines)

    df = _filter_results(df)

    lines.extend([
        "## Dataset overview",
        "",
        f"- Total rows after deduplication: {len(df)}",
        f"- Columns: {', '.join(df.columns)}",
        "",
    ])

    # Try to identify numeric accuracy columns.
    numeric_cols = df.select_dtypes(include="number").columns.tolist()
    candidate_cols = [c for c in numeric_cols if "acc" in c.lower() or "accuracy" in c.lower()]

    lines.append("## Summary statistics")
    lines.append("")
    if candidate_cols:
        lines.append("| Metric | Mean | Std | Min | Max |")
        lines.append("|---|---|---|---|---|")
        for col in candidate_cols:
            mean = _format_number(df[col].mean())
            std = _format_number(df[col].std())
            minv = _format_number(df[col].min())
            maxv = _format_number(df[col].max())
            lines.append(f"| {col} | {mean} | {std} | {minv} | {maxv} |")
    else:
        lines.append("_No obvious accuracy columns found (looking for columns containing 'acc' or 'accuracy')._")
    lines.append("")

    # Per-seed breakdown if seed column exists.
    if "seed" in df.columns:
        lines.append("## Per-seed breakdown")
        lines.append("")
        if candidate_cols:
            lines.append("| Seed | " + " | ".join(candidate_cols) + " |")
            lines.append("|" + "---|" * (len(candidate_cols) + 1))
            for seed, group in df.groupby("seed"):
                vals = [_format_number(group[col].mean()) for col in candidate_cols]
                lines.append(f"| {seed} | " + " | ".join(vals) + " |")
        else:
            lines.append("_No accuracy columns available for per-seed breakdown._")
        lines.append("")

    # Per-task breakdown if task column exists.
    if "task" in df.columns and candidate_cols:
        lines.append("## Per-task breakdown")
        lines.append("")
        lines.append("| Task | " + " | ".join(candidate_cols) + " |")
        lines.append("|" + "---|" * (len(candidate_cols) + 1))
        for task, group in df.groupby("task"):
            vals = [_format_number(group[col].mean()) for col in candidate_cols]
            lines.append(f"| {task} | " + " | ".join(vals) + " |")
        lines.append("")

    lines.extend([
        "## Interpretation",
        "",
        "This is a machine-generated first pass. Verify any numbers against the source CSV before citing them.",
        "",
    ])
    if candidate_cols:
        best_col = candidate_cols[0]
        mean_val = df[best_col].mean()
        std_val = df[best_col].std()
        lines.append(
            f"- Mean `{best_col}` across all rows: {_format_number(mean_val)} "
            f"± {_format_number(std_val)}."
        )
        if "task" in df.columns:
            task_means = df.groupby("task")[best_col].mean().sort_values(ascending=False)
            if not task_means.empty:
                best_task = task_means.index[0]
                lines.append(f"- Highest mean `{best_col}` by task: **{best_task}** ({_format_number(task_means.iloc[0])}).")
    else:
        lines.append("- No accuracy metric identified; provide a column name to the consultant if you want focused analysis.")
    lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("## Active lessons")
    lines.append("")
    lessons = read_recent_lessons(n=5)
    lines.append(lessons if lessons.strip() else "_(no lessons yet)_")
    lines.append("")

    return "\n".join(lines)


def main(argv: Optional[List[str]] = None) -> int:
    """Generate and save the statistics consultant report."""
    parser = argparse.ArgumentParser(description="Generate a statistics report for experiment results.")
    parser.add_argument("--dry-run", action="store_true", help="Print to stdout instead of writing to vault")
    args = parser.parse_args(argv)

    body = _build_report(dry_run=args.dry_run)

    if args.dry_run:
        print(body)
        return 0

    stamp = datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
    path = write_note(
        "consultant",
        f"{stamp}.md",
        body,
        frontmatter={"timestamp": stamp, "source": "consult"},
    )
    log_session("consult", path)
    print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
