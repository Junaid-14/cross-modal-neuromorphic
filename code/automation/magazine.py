#!/usr/bin/env python3
"""Generate the daily research magazine issue for the M7 project.

Usage:
    python code/automation/magazine.py [--dry-run]

The script queries the local research RAG and (best-effort) arXiv RSS feeds,
then writes a dated issue to knowledge/10-Research-Magazine/.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import xml.etree.ElementTree as ET
from datetime import datetime
from pathlib import Path
from typing import List, Optional
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

# Make code/ importable so we can use `import automation`.
CODE_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(CODE_DIR))

from automation import read_recent_lessons, write_note
from automation.vault import log_session

REPO_ROOT = CODE_DIR.parent
ARXIV_CATEGORIES = ["cs.NE", "cs.LG", "cs.CV"]
USER_AGENT = "M7-Research-Magazine/1.0 (local automation; +https://none)"


def _run_rag_query(query: str, *, k: int = 5) -> str:
    """Run a local RAG query and return the context block."""
    cmd = [
        sys.executable,
        str(REPO_ROOT / "code" / "rag_query.py"),
        query,
        "--context",
        "--fallback-embedder",
        "-k",
        str(k),
    ]
    try:
        result = subprocess.run(cmd, capture_output=True, text=True, cwd=str(REPO_ROOT), timeout=60)
        if result.returncode != 0:
            return f"(RAG query failed: {result.stderr.strip()[:200]})"
        return result.stdout.strip()
    except Exception as exc:  # noqa: BLE001
        return f"(RAG query error: {exc})"


def _ingest_rag() -> None:
    """Refresh the local RAG index if possible."""
    cmd = [
        sys.executable,
        str(REPO_ROOT / "code" / "rag_ingest.py"),
        "--fallback-embedder",
    ]
    try:
        subprocess.run(cmd, cwd=str(REPO_ROOT), timeout=120, check=False)
    except Exception:  # noqa: BLE001
        pass  # Best-effort ingestion; don't block the magazine.


def _fetch_arxiv_rss(category: str, *, max_items: int = 5) -> List[dict]:
    """Fetch recent arXiv entries for a category."""
    url = f"http://export.arxiv.org/rss/{category}"
    req = Request(url, headers={"User-Agent": USER_AGENT})
    try:
        with urlopen(req, timeout=20) as response:  # noqa: S310
            data = response.read()
    except (HTTPError, URLError, TimeoutError) as exc:
        return [{"title": f"Could not fetch {category}: {exc}", "link": "", "summary": ""}]

    try:
        root = ET.fromstring(data)
    except ET.ParseError as exc:
        return [{"title": f"Parse error for {category}: {exc}", "link": "", "summary": ""}]

    items: List[dict] = []
    for item in root.iter("item"):
        title = (item.findtext("title") or "").strip()
        link = (item.findtext("link") or "").strip()
        summary = (item.findtext("description") or "").strip()
        # Strip HTML-ish tags for readability.
        summary = summary.replace("<p>", "").replace("</p>", " ").replace("<br />", " ")
        if title:
            items.append({"title": title, "link": link, "summary": summary[:400]})
        if len(items) >= max_items:
            break
    return items


def _issue_number() -> int:
    """Count existing issues to assign the next issue number."""
    folder = REPO_ROOT / "knowledge" / "10-Research-Magazine"
    if not folder.exists():
        return 1
    return len([p for p in folder.iterdir() if p.suffix == ".md"]) + 1


def _build_issue(*, dry_run: bool = False) -> str:
    """Compose the markdown body of the magazine issue."""
    today = datetime.now().strftime("%Y-%m-%d")
    issue = _issue_number()

    lines = [
        f"# Research Magazine — Issue #{issue} ({today})",
        "",
        "Generated by `/research-magazine`.",
        "",
        "Rate each item with `keep`, `meh`, or `skip` to tune tomorrow's issue.",
        "",
        "---",
        "",
        "## From the local vault",
        "",
    ]

    # RAG-grounded sections.
    rag_queries = {
        "Papers": "recent neuromorphic computing papers spiking neural networks",
        "Tools": "neuromorphic simulation tools sPyNNaker snntorch tonic datasets",
        "Models": "cross-modal learning models continual learning memory mechanisms",
    }
    rag_contexts: dict[str, str] = {}
    for section, query in rag_queries.items():
        ctx = _run_rag_query(query, k=3)
        rag_contexts[section] = ctx
        lines.append(f"### {section}")
        lines.append("")
        if not ctx.strip() or ctx.startswith("("):
            lines.append("_No matching items in the local vault._")
        else:
            # Present the context as a single curated item.
            lines.append(ctx)
        lines.append("")
        lines.append("- rating:")
        lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("## From arXiv (best-effort)")
    lines.append("")

    arxiv_items: List[dict] = []
    for cat in ARXIV_CATEGORIES:
        arxiv_items.extend(_fetch_arxiv_rss(cat, max_items=2))

    if not arxiv_items or all(not item.get("title") or item["title"].startswith("Could") for item in arxiv_items):
        lines.append("_No arXiv items today (network unavailable or RSS unreachable)._")
        lines.append("")
    else:
        for item in arxiv_items:
            title = item.get("title", "Untitled")
            link = item.get("link", "")
            summary = item.get("summary", "")
            lines.append(f"- **{title}**" + (f" — [link]({link})" if link else ""))
            if summary:
                lines.append(f"  {summary}")
            lines.append("  - rating:")
            lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("## Active lessons")
    lines.append("")
    lessons = read_recent_lessons(n=5)
    lines.append(lessons if lessons.strip() else "_(no lessons yet)_")
    lines.append("")

    return "\n".join(lines)


def main(argv: Optional[List[str]] = None) -> int:
    """Generate and save the daily research magazine issue."""
    parser = argparse.ArgumentParser(description="Generate today's research magazine issue.")
    parser.add_argument("--dry-run", action="store_true", help="Print to stdout instead of writing to vault")
    parser.add_argument("--no-ingest", action="store_true", help="Skip refreshing the RAG index")
    args = parser.parse_args(argv)

    if not args.no_ingest:
        _ingest_rag()

    body = _build_issue(dry_run=args.dry_run)

    if args.dry_run:
        print(body)
        return 0

    today = datetime.now().strftime("%Y-%m-%d")
    path = write_note(
        "magazine",
        f"{today}.md",
        body,
        frontmatter={
            "issue_number": _issue_number(),
            "date": today,
            "source": "research-magazine",
        },
    )
    log_session("research-magazine", path)
    print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
